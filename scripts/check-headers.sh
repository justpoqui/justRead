# Fail if any source file lacks the Apache-2.0 SPDX header.
set -euo pipefail
cd "$(dirname "$0")/.."

missing=0
while IFS= read -r f; do
  if ! head -n 5 "$f" | grep -q "SPDX-License-Identifier: Apache-2.0"; then
    echo "missing license header: $f"
    missing=1
  fi
done < <(git ls-files --cached --others --exclude-standard \
  '*.rs' '*.ts' '*.svelte' '*.mjs' '*.js' '*.py' '*.sh' '*.css' '*.html' '*.toml' '*.yml' \
  | grep -v -E '(^|/)(gen|node_modules|dist|autogenerated)/' | grep -v -E '^(rustfmt\.toml|pnpm-lock)')

exit $missing
